"""The claim store: read, order, write. The reconciliation layer, not a memory.

Supersedes ``agent/memory.py`` + ``agent/user_memory.py`` (IMPLEMENTATION §10). Two
things from the note store are kept deliberately, because §10's migration row names
both and because each encodes a failure that was real:

* **``status``** survives as ``Claim.status`` (firm | tentative), orthogonal to
  authority. A tentative measurement and a firm literature claim are different, and
  collapsing them loses the distinction a reviewer most wants.
* **the thin-literature signal** survives as :func:`thin_literature`, DERIVED rather
  than stored. ``memory.Tension.thin`` was a boolean a writer could get wrong; here
  the signal is the source URI itself -- a knowledge claim with no ``pmid:``/``doi:``
  behind it is thin by construction, and no amount of optimism in a writer can make
  it read otherwise. "If a lookup returns nothing, say the literature is thin."

**What this module refuses to do.** No dedupe, no LLM merging, no recency resolution,
no background consolidation, no decay, no scoring. §10.5 is explicit that those
mechanisms exist to manage noisy conversational streams, that they destroyed the audit
trails of consumer memory systems, and that none of Panoscope's claim classes are
noisy. :meth:`ClaimStore.about` therefore ORDERS and never merges: two claims that
contradict each other both come back, highest authority first, and the disagreement is
the product.

**Two gates, and they are deliberately different.**

* *Retrieval* (:meth:`ClaimStore.about`) filters by scope -- §10.4, "scope filters
  before retrieval, never after" -- and records a decision for each claim it withheld,
  so a missing claim can still be accounted for.
* *Use* (:meth:`ClaimStore.cite`, :func:`assess`) **raises**. CLAUDE.md: "Scope is
  enforced fail-closed... A claim used outside its scope is an error, not a warning."
  A filter that silently returns nothing and a function that refuses are not the same
  safety property, and the second is the one that catches a caller who already has a
  claim in hand and is about to put it in an answer.

**Why reference data cannot supply a value here.** Structurally, not by documentation:
``Claim`` has no numeric field at all, so there is nothing for a curated edge to
supply; ``object`` holds an entity id or free text, never a statistic. And
:func:`write_claim` refuses everything but LAB, because §10.5 allows exactly two
writers and the git-tracked JSON-per-file store of §10.6 holds exactly one class.
Measurement claims are regenerated by the pipeline from the dataset tree; a measurement
claim arriving through the biologist's commit path would be a number with no method
behind it.

Clock-free: ``created`` is whatever the caller minted. A ``now()`` in here would put a
timestamp into bytes that are hashed into the golden record.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Final

from panoscope.claims.evaluability import Evaluability, evaluability
from panoscope.claims.transfer import BLOCKED, TransferResult, transfer_check
from panoscope.types.claim import Authority, Claim, by_authority
from panoscope.types.conditions import Condition, Conditions, Provenance
from panoscope.types.measured import FrameRef, MeasuredWorld
from panoscope.types.subject import Entity, EntityKind, Subject, subject
from panoscope.types.trace import Trace, Traced, ref

SEED_RELPATH: Final = "claims/canonical_markers_seed.json"
"""Where the canonical-marker seed lives under the data root.

A relative path and not an absolute one: the data root is per-install and resolving it
here would mean importing ``agent.config``'s singleton, which §7 Phase C exists to
dissolve. Callers pass a path; this constant only spares them inventing the spelling.
"""

SUPPORT: Final[tuple[str, ...]] = ("supported", "weak", "none")


class OutOfScope(ValueError):
    """Raised when a claim is USED outside the scope it was committed under.

    Fail-closed, and an error rather than a downgrade. A claim applied out of scope is
    the lab's hard-won caveat about one FFPE block silently qualifying a different
    one -- which reads, in the report, exactly like knowledge.
    """


class Retracted(ValueError):
    """Raised when a retracted or superseded claim is cited.

    Retrieval still SHOWS these (§10.3: silent dropping is the failure mode) so a
    reviewer can see that the lab changed its mind, and what it changed its mind
    from. Citing one in an answer is a different act, and it is refused.
    """


class NotCommittable(ValueError):
    """Raised when something other than a LAB claim is written to the lab store."""


class BadSeed(ValueError):
    """Raised for a canonical-marker seed file that cannot be trusted as read.

    Loud rather than lenient, and the one place in this module where that is not a
    style preference: this file is the replacement for an UNCITED path that currently
    reaches the confidence band (``verdict._is_canonical`` -> driver selection), so a
    silently half-read seed would restore the exact failure it exists to remove.
    """


# --------------------------------------------------------------------------- #
# Serialisation. Claim <-> plain JSON, one file per claim (§10.6).
# --------------------------------------------------------------------------- #
def _entity_to_dict(e: Entity) -> dict[str, Any]:
    return {"kind": e.kind.value, "id": e.id, "label": e.label}


def _entity_from_dict(d: dict[str, Any]) -> Entity:
    return Entity(EntityKind(d["kind"]), str(d["id"]), str(d.get("label", "")))


def _subject_to_dict(s: Subject) -> dict[str, Any]:
    return {"shape": s.shape,
            "parts": [{"role": r, **_entity_to_dict(e)} for r, e in s.parts]}


def _subject_from_dict(d: dict[str, Any]) -> Subject:
    """Rebuilt through ``subject()``, never by constructing ``Subject`` directly.

    The constructor is what canonicalises symmetric roles and sorts member sets, so a
    directly-built Subject can fail to compare equal to the same thing built properly
    -- and ``Subject.key`` is the join key reconciliation depends on.
    """
    roles: dict[str, list[Entity]] = {}
    for p in d["parts"]:
        roles.setdefault(str(p["role"]), []).append(_entity_from_dict(p))
    return subject(str(d["shape"]),
                   **{r: (v[0] if len(v) == 1 else v) for r, v in roles.items()})


def _condition_to_dict(c: Condition) -> dict[str, Any]:
    return {"value": c.value, "provenance": c.provenance.value}


def _conditions_to_dict(c: Conditions) -> dict[str, Any]:
    out: dict[str, Any] = {
        n: _condition_to_dict(getattr(c, n))
        for n in ("assay", "modality", "tissue", "method", "segmentation", "fixation")
    }
    out["frames"] = [{"kind": f.kind.value, "name": f.name,
                      "digest": f.digest, "size": f.size} for f in c.frames]
    return out


def _conditions_from_dict(d: dict[str, Any]) -> Conditions:
    def cond(name: str) -> Condition:
        raw = d[name]
        return Condition(raw["value"], Provenance(raw["provenance"]))

    return Conditions(
        assay=cond("assay"), modality=cond("modality"), tissue=cond("tissue"),
        method=cond("method"), segmentation=cond("segmentation"),
        fixation=cond("fixation"),
        frames=tuple(FrameRef(EntityKind(f["kind"]), str(f["name"]),
                              str(f["digest"]), int(f["size"]))
                     for f in d.get("frames", ())),
    )


def to_dict(claim: Claim) -> dict[str, Any]:
    """A JSON-safe dict. Hand-written rather than ``dataclasses.asdict``.

    ``asdict`` would flatten ``Authority`` to its integer and ``Subject.parts`` to
    nested tuples, so the file would be unreadable in a git diff -- and a lab store
    nobody can read in review is a lab store nobody reviews.
    """
    return {
        "id": claim.id,
        "subject": _subject_to_dict(claim.subject),
        "predicate": claim.predicate,
        "object": claim.object,
        "authority": claim.authority.name.lower(),
        "source": claim.source,
        "conditions": (None if claim.conditions is None
                       else _conditions_to_dict(claim.conditions)),
        "depends_on": [_entity_to_dict(e) for e in claim.depends_on],
        "scope": claim.scope,
        "status": claim.status,
        "valid": claim.valid,
        "superseded_by": claim.superseded_by,
        "created": claim.created,
        "author": claim.author,
        "tension": list(claim.tension),
        "licence": claim.licence,
        "spans": list(claim.spans),
        "spec_version": claim.spec_version,
    }


def from_dict(d: dict[str, Any]) -> Claim:
    """Rebuild a claim. Every validation in ``Claim.__post_init__`` runs on read.

    Deliberate: a claim file edited by hand -- which is the point of git-tracked JSON
    -- is exactly where a malformed scope or an unresolvable source would enter, and
    the fail-closed gates are worth nothing if they only run on the write.
    """
    cond = d.get("conditions")
    return Claim(
        id=str(d["id"]),
        subject=_subject_from_dict(d["subject"]),
        predicate=str(d["predicate"]),
        object=d.get("object"),
        authority=Authority[str(d["authority"]).upper()],
        source=str(d["source"]),
        conditions=None if cond is None else _conditions_from_dict(cond),
        depends_on=tuple(_entity_from_dict(e) for e in d.get("depends_on", ())),
        # NO default. "study" is the unkeyed rung, so a file that simply forgot its
        # scope key would apply in EVERY study -- the same silent widening that
        # ``memory._note_from_dict`` was fixed for one module over. "" does not parse,
        # so ``Claim.__post_init__`` raises ``BadScope`` naming the claim id and the
        # four legal spellings. A read is where a malformed scope enters, and the
        # fail-closed gate is worth nothing if it only runs on the write.
        scope=str(d.get("scope", "")),
        status=str(d.get("status", "firm")),
        valid=str(d.get("valid", "active")),
        superseded_by=d.get("superseded_by"),
        created=str(d.get("created", "")),
        author=d.get("author"),
        tension=tuple(str(x) for x in d.get("tension", ())),
        licence=d.get("licence"),
        spans=tuple(str(x) for x in d.get("spans", ())),
        spec_version=str(d.get("spec_version", "0.1")),
    )


# --------------------------------------------------------------------------- #
# The store
# --------------------------------------------------------------------------- #
@dataclass(frozen=True, slots=True)
class ClaimStore:
    """Claims in the order they were loaded. Immutable; :meth:`plus` returns a new one.

    A tuple and a linear scan, not an index. The lab store is one JSON file per claim
    and the seeded curated set is ~66 pairs; an index would be a second copy of the
    truth to keep in sync, and a dict field would break the frozen/hashable contract
    every other type in this codebase holds to.

    # ponytail: linear scan. Build an index when a store is large enough to measure.
    """

    claims: tuple[Claim, ...] = ()

    def __len__(self) -> int:
        return len(self.claims)

    def __iter__(self):
        return iter(self.claims)

    def plus(self, *claims: Claim) -> "ClaimStore":
        return ClaimStore(self.claims + tuple(claims))

    def get(self, claim_id: str) -> Claim | None:
        return next((c for c in self.claims if c.id == claim_id), None)

    def about(self, subject_key: str, context: str) -> Traced[tuple[Claim, ...]]:
        """Every claim about one subject here, highest authority first, NEVER merged.

        Scope filters before the result is formed (§10.4), and each withheld claim
        gets a decision naming itself -- so "no lab knowledge about this" and "the
        lab's knowledge about this is scoped to another dataset" are distinguishable
        afterwards, which they are not if the filter is silent.

        Contradictory claims all survive. There is no resolution rule here because
        §10.2 says there is none: conflicts are grouped and displayed.
        """
        t = Trace()
        kept: list[Claim] = []
        for c in self.claims:
            if c.subject.key != subject_key:
                continue
            if not c.applies_in(context):
                t.note("claims:out_of_scope", "withheld",
                       (f"scope {c.scope} does not apply in {context}",),
                       (ref(f"claim:{c.id}"),))
                continue
            kept.append(c)
        return t.done(by_authority(tuple(kept)))

    def cite(self, claim_id: str, context: str) -> Claim:
        """Fetch a claim FOR USE. Raises rather than returning something unusable.

        The three refusals are the three ways a cited claim can be wrong without
        looking wrong in the rendered sentence: it does not exist, it was retracted,
        or it belongs to another scope.
        """
        c = self.get(claim_id)
        if c is None:
            raise KeyError(f"no claim {claim_id!r} in this store")
        if c.valid != "active":
            raise Retracted(
                f"{claim_id}: claim is {c.valid}"
                + (f", superseded by {c.superseded_by}" if c.superseded_by else "")
                + "; it is shown in review but may not be cited"
            )
        if not c.applies_in(context):
            raise OutOfScope(
                f"{claim_id}: scope {c.scope!r} does not apply in {context!r}. "
                "Scope is fail-closed: a claim used outside its scope is an error."
            )
        return c


# --------------------------------------------------------------------------- #
# The ordered assessment: scope, then capability, then -- sometimes -- conditions
# --------------------------------------------------------------------------- #
@dataclass(frozen=True, slots=True)
class Assessment:
    """One claim, adjudicated. Both halves of §7.5's split, in the stated order."""

    claim: Claim
    evaluable: Evaluability
    transfer: TransferResult

    @property
    def usable(self) -> bool:
        """Capability first. A claim whose entities were never measured here is not
        made usable by its conditions matching, and §7.6 is the reason round: the
        measurement adjudicates the claim, never the claim its own conditions."""
        return self.evaluable.usable and self.transfer.action != BLOCKED


def assess(claim: Claim, world: MeasuredWorld, context: Conditions,
           where: str) -> Traced[Assessment]:
    """Scope gate, then evaluability, then the condition deltas (IMPLEMENTATION §5).

    The order lives here rather than in each caller, which is the difference between
    an ordering rule and an ordering convention. The scope gate RAISES: ``assess`` is
    a use, not a retrieval, and CLAUDE.md makes out-of-scope use an error.
    """
    if not claim.applies_in(where):
        raise OutOfScope(
            f"{claim.id}: scope {claim.scope!r} does not apply in {where!r}. "
            "Scope is fail-closed: filter with ClaimStore.about before assessing."
        )
    t = Trace()
    ev = t.absorb(evaluability(claim, world))
    tr = t.absorb(transfer_check(claim, context))
    return t.done(Assessment(claim=claim, evaluable=ev, transfer=tr))


# --------------------------------------------------------------------------- #
# The thin-literature signal, kept from agent/memory.py (§10) -- derived, not stored
# --------------------------------------------------------------------------- #
_CITATION_SCHEMES: Final[frozenset[str]] = frozenset({"pmid", "doi"})


def thin_literature(claim: Claim) -> bool:
    """True when a knowledge claim has no resolvable citation behind it.

    Scoped to CURATED and LITERATURE on purpose. A measurement claim sourced to a
    content-addressed file is not "thin literature", it is not literature; and a lab
    claim's authority is the biologist, whose judgement does not become thin for
    want of a PMID. Calling either one thin would turn an honest signal into noise
    the interface learns to ignore.
    """
    if claim.authority not in (Authority.CURATED, Authority.LITERATURE):
        return False
    return claim.source.partition(":")[0] not in _CITATION_SCHEMES


# --------------------------------------------------------------------------- #
# IO
# --------------------------------------------------------------------------- #
def write_claim(claim: Claim, directory: Path | str) -> Path:
    """Commit ONE lab claim to the git-tracked store. LAB only (§10.5, §10.6).

    The refusal is the enforcement of "only the biologist commits". Measurement
    claims are regenerated by the pipeline from the dataset tree and hold references
    into it; curated and literature claims are imported from their sources. A claim
    of any of those three arriving down the biologist's commit path is knowledge with
    the wrong provenance stamped on it, which is the one failure §10.2 says collapses
    the design.
    """
    if claim.authority is not Authority.LAB:
        raise NotCommittable(
            f"{claim.id}: only LAB claims are committed to the tracked store "
            f"(got {claim.authority.name}). Measurement claims are regenerated by "
            "the pipeline; curated and literature claims are imported."
        )
    d = Path(directory)
    d.mkdir(parents=True, exist_ok=True)
    path = d / f"{claim.id}.json"
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(to_dict(claim), fh, indent=2, ensure_ascii=False, sort_keys=True)
        fh.write("\n")
    return path


def load_dir(directory: Path | str) -> ClaimStore:
    """Every ``*.json`` under a directory, in filename order.

    Sorted so the store's order -- which ``by_authority`` preserves within an
    authority, and which is therefore what the biologist sees -- does not depend on
    the filesystem's iteration order.
    """
    d = Path(directory)
    if not d.is_dir():
        return ClaimStore()
    out: list[Claim] = []
    for path in sorted(d.glob("*.json")):
        with open(path, encoding="utf-8") as fh:
            out.append(from_dict(json.load(fh)))
    return ClaimStore(tuple(out))


# --------------------------------------------------------------------------- #
# The canonical-marker seed -> CURATED claims
# --------------------------------------------------------------------------- #
def load_canonical_markers(path: Path | str, *, scope: str = "lab") -> ClaimStore:
    """The ``(cell_type, gene)`` canonical-marker seed, as CURATED claims.

    This replaces an **uncited** path. ``agent/annotation.py``'s bundled map feeds
    ``verdict._is_canonical`` -> driver selection -> the confidence band, today, with
    no source attached to any pair. Every claim this produces carries a source, and
    the pairs that have no citation say so rather than borrowing one.

    **An uncited pair is kept, and is honest about it.** ``support: "none"`` means the
    live lookup returned nothing. The three available spellings were: drop it, which
    silently shrinks the canonical set and changes the band with no record; invent a
    PMID, which is the worst failure this project can produce; or source it to the
    thing that actually asserts it. The third is what happens -- the pair is sourced
    to the seed file itself, content-addressed as ``file:sha256:<digest>``, with
    ``status="tentative"``, and :func:`thin_literature` returns True for it. That is
    precisely true: the bundled map asserts this pair and nothing else does. It is
    also checkable, because the digest resolves to the exact bytes that were read.

    **``off_panel`` is read and ignored.** The predicate says so -- a canonical marker
    is canonical "whether or not it is on the panel; the frame decides measurability,
    the claim does not". Letting it onto the claim would bake one study's panel into
    knowledge meant to outlive it, and would make an off-panel marker's absence read
    as evidence, which is the panel-absence rule inverted.

    ``scope`` defaults to ``lab``: canonical markers are not about any one dataset, so
    they are not manifest-sourced and :func:`transfer_check` gives them a provenance
    stamp rather than the verdict §7.4 measured at 0.000 bits. A vendor panel
    annotation loaded the same way would pass ``dataset:<id>`` and get real deltas.
    """
    p = Path(path)
    try:
        text = p.read_text(encoding="utf-8")
    except FileNotFoundError:
        raise BadSeed(
            f"no canonical-marker seed at {p}. It is produced by a live lookup pass; "
            "this loader never invents one."
        ) from None
    try:
        raw = json.loads(text)
    except json.JSONDecodeError as exc:
        raise BadSeed(f"{p}: not valid JSON ({exc})") from None

    pairs = raw.get("pairs") if isinstance(raw, dict) else None
    if not isinstance(pairs, list) or not pairs:
        raise BadSeed(f"{p}: no 'pairs' array; nothing to load")

    # Content-addressed over the bytes actually read, so the source of an uncited
    # pair resolves to this exact file and not to "a file by that name".
    summary = raw.get("summary")
    if isinstance(summary, dict) and "total" in summary \
            and int(summary["total"]) != len(pairs):
        raise BadSeed(
            f"{p}: summary says {summary['total']} pairs, the array holds "
            f"{len(pairs)}. A half-written seed silently shrinks the canonical set."
        )

    uncited_source = "file:sha256:" + hashlib.sha256(text.encode("utf-8")).hexdigest()
    out: list[Claim] = []
    seen: dict[str, Claim] = {}

    for i, pair in enumerate(pairs):
        if not isinstance(pair, dict) or "cell_type" not in pair or "gene" not in pair:
            raise BadSeed(f"{p}: pair {i} is missing cell_type or gene")
        ct, g = str(pair["cell_type"]), str(pair["gene"])
        support = str(pair.get("support", "")).strip()
        if support not in SUPPORT:
            raise BadSeed(
                f"{p}: pair {i} ({g}/{ct}) has support {support!r}; "
                f"expected one of {SUPPORT}"
            )
        pmid = str(pair.get("pmid") or "").strip()
        if support == "none" and pmid:
            # A record that says the lookup found nothing and still carries an
            # identifier is the exact shape of a fabricated citation. Refuse it
            # rather than pick one of the two halves to believe.
            raise BadSeed(
                f"{p}: pair {i} ({g}/{ct}) declares support='none' but carries "
                f"pmid {pmid!r}. One of the two is wrong; neither is guessed at here."
            )
        if support != "none" and not pmid:
            raise BadSeed(
                f"{p}: pair {i} ({g}/{ct}) declares support={support!r} with no pmid"
            )

        cid = f"curated:marks:{g}:{ct}"
        claim = Claim(
            id=cid,
            subject=subject("gene", g=Entity(EntityKind.GENE, g)),
            predicate="marks",
            object=ct,
            authority=Authority.CURATED,
            # depends_on carries the cell type so evaluability gates it against the
            # ANNOTATION frame, not the panel. Without it a marks-edge for a label
            # this study never assigned would read as perfectly evaluable.
            depends_on=(Entity(EntityKind.CELL_TYPE, ct),),
            source=(f"pmid:{pmid}" if pmid else uncited_source),
            scope=scope,
            # "weak" and "none" are both tentative; only a supported, cited pair is
            # firm. status is orthogonal to authority and is kept from the note
            # store for exactly this: how firmly it was said.
            status=("firm" if support == "supported" else "tentative"),
            licence=str(pair.get("licence") or "") or None,
        )

        # A repeated ROW is not a repeated CLAIM. ``annotation.py`` lists DCN and
        # COL1A1 under Stromal in both its on-panel and off-panel maps, so the seed
        # carries each twice, identical but for ``off_panel`` -- which is exactly
        # the field a claim must not carry. Two rows that produce the same claim are
        # one claim; nothing is merged, because there is nothing to merge.
        #
        # Two rows that produce DIFFERENT claims for one pair are a different
        # matter and still raise: that is two citations sharing an id, which breaks
        # the click-back the id exists for, and picking one of them is the
        # resolve-by-order rule §10.5 refuses.
        if cid in seen:
            if seen[cid] == claim:
                continue
            raise BadSeed(
                f"{p}: pair {i} ({g}/{ct}) collides with an earlier pair but "
                f"differs ({seen[cid].source}/{seen[cid].status} vs "
                f"{claim.source}/{claim.status}). Two claims may not share an id, "
                "and neither is dropped in favour of the other here."
            )
        seen[cid] = claim
        out.append(claim)

    return ClaimStore(tuple(out))
